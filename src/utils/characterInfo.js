// ============================================================
// Get Character Info
// ============================================================

export function getCharacterInfo(characterId) {
  const id = String(characterId).trim();
  return (
    characterInfo[id] || {
      displayName: "Unknown",
      iconPath: null,
    }
  );
}


// ============================================================
// Get All Character Info
// ============================================================

export function getAllCharacterInfo() {
  return Object.entries(characterInfo).map(
    ([id, info]) => ({
      id: String(id),
      ...info,
    })
  );
}


